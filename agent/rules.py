"""Быстрый слой предупреждений без LLM: правила по ключевым словам и по asks_for этапа.

ТЗ: «Предупреждения не зависят от LLM. warning формируется правилами». Модель отвечает
секунды, а красная плашка должна появиться за доли секунды после фразы мошенника.
Правило — сочетание признаков (например, «код» + «смс»), а не одно слово: настоящий
банк тоже говорит «карта» и «счёт». Фразы вида «никому не сообщайте код» (так
предупреждает настоящий банк) отсеиваются вето-словами.

Метрики: eval — правило сработало на caller в 45 из 45 фрагментов с мошенничеством, на 13 обычных
звонках 0 срабатываний; dialogs.jsonl — на 4,2 % предложений scammer и 1,7 % предложений target
(пранкеры повторяют за мошенником; болтовни у обоих много, поэтому доля scammer невелика).
"""

from __future__ import annotations

import re
from dataclasses import dataclass

from contracts import Stage
from rag.chunks import tokenize

STAGE_OVERLAP = 0.7  # доля основ из asks_for, которые должны встретиться в речи (как в policy)

_SENTENCE = re.compile(r"[^.!?…\n]+[.!?…]*")


@dataclass(frozen=True)
class RuleHit:
    """Сработавшее правило: категория для плашки и предложение, где оно сработало."""

    label: str
    quote: str


@dataclass(frozen=True)
class _Rule:
    label: str
    # Все группы обязательны; в группе достаточно любого термина.
    groups: tuple[tuple[str, ...], ...]
    # Если в предложении есть любой из этих терминов — правило не срабатывает.
    veto: tuple[str, ...] = ()


# Термин — начало слова («перев» ловит «переведите», «перевод»); «$» на конце — слово целиком
# (так «карт$» не ловит «картошку»); термин через «_» — подряд идущие слова («не_клад»).
def _w(s: str) -> tuple[str, ...]:
    return tuple(s.split())


CODE = _w("код$ кода$ коду$ кодом$ коде$ коды$ кодов$ пароль пароля паролю одноразов")
SMS = _w("смс sms сообщен прид пришл пришед высл отправ push пуш")
CARD = _w("карт$ карты$ карту$ картой$ карте$ картам карточк")
SCHET = _w("счет$ счета$ счету$ счетом$ счете$ счета$ счетов$ счетах$")
MONEY = _w("деньг средств сумм рубл тысяч сбережен остат сбп") + CARD + SCHET
# Что просит назвать/прислать мошенник.
ASK = _w(
    "назов продикт скаж сообщит сообщай диктуй диктов пришл отправ сфот введ укаж назыв "
    "подтверд предостав"
)
# Предупреждения настоящих банков и бытовые реплики: «никому не сообщайте код», «код домофона».
SAFE = _w("никому не_сообщ не_называ не_говор не_диктуй не_передав не_пересыл домофон")

_RULES: tuple[_Rule, ...] = (
    # --- код из СМС ---
    _Rule("код из СМС", (CODE, SMS), SAFE),
    _Rule("код из СМС", (ASK, CODE), SAFE),
    _Rule("код из СМС", (_w("смс sms сообщен цифр"), _w("назов продикт диктов скаж")), SAFE),
    # --- перевод денег ---
    _Rule("перевод денег", (_w("переве перево"), MONEY), _w("не_переве не_перево никому перевел перевёл перевожу перевели")),
    _Rule("перевод денег", (_w("скин скинь кин закин отправь вышли"), _w("тысяч деньг рубл сумм")), SAFE),
    _Rule(
        "перевод денег",
        (_w("переводи$ переводите$ переведи$ переведите$ переведешь$ перевод_сделай переводить$"),),
        _w("не_переве не_перево никому"),
    ),
    _Rule(
        "перевод денег",
        (_w("реквизит номер_карты номер_счета"), _w("запиш записыв диктую скину кину отправ переводи оплат сюда")),
        SAFE,
    ),
    _Rule(
        "оплата по требованию",
        (_w("оплати$ оплатите$ оплату$ оплатить$ оплачиваешь$"), _w("сначала сейчас срочно сегодня брон услуг страховк отдых")),
    ),
    # --- безопасный счёт ---
    _Rule("безопасный счёт", (_w("безопасн защищен защитн резервн проверочн"), SCHET + _w("ячейк"))),
    _Rule("безопасный счёт", (_w("резервн"), _w("ячейк"))),
    # --- наличные / банкомат / курьер ---
    _Rule(
        "наличные / банкомат / курьер",
        (_w("снят снять снима снимит снимай снимеш внес внос положит обналич"), _w("налич банкомат терминал купюр")),
    ),
    _Rule(
        "наличные / банкомат / курьер",
        (_w("налич"), _w("снят снимит подъед заберет забер передат дома держ")),
    ),
    _Rule("наличные / банкомат / курьер", (_w("банкомат"), _w("иди идеш идите подойд дойд найд"))),
    # --- данные карты ---
    _Rule("данные карты", (_w("cvv cvc"),), SAFE),
    _Rule("данные карты", (_w("три_цифры срок_действ"), _w("оборот обратн карт срок")), SAFE),
    _Rule("данные карты", (ASK, CARD, _w("номер срок оборот обратн данн цифр реквизит пин")), SAFE),
    # --- установка приложения / доступ к экрану ---
    _Rule(
        "установка приложения / доступ к экрану",
        (_w("скача установ поставь загруз"), _w("приложен программ")),
        SAFE + _w("официальн"),
    ),
    _Rule(
        "установка приложения / доступ к экрану",
        (_w("anydesk эникдеск анидеск тимвьювер teamviewer rustdesk рустдеск удаленн_доступ демонстрац_экран"),),
    ),
    _Rule(
        "установка приложения / доступ к экрану",
        (_w("включ покаж показ демонстр транслир"), _w("экран")),
    ),
    # --- кредит ---
    _Rule(
        "кредит",
        (_w("оформи оформл возьми берит взять подайт одобр"), _w("кредит займ заем ссуд")),
        _w("кредитн_карт кредитк"),
    ),
    _Rule("кредит", (_w("оформи оформл"), _w("встречн"))),
    # --- паспорт / СНИЛС ---
    _Rule("паспорт / СНИЛС", (ASK, _w("паспорт снилс$ снилса$ серию инн$")), SAFE),
    _Rule("паспорт / СНИЛС", (_w("снилс$ снилса$ снилсом$ снилсе$"),), SAFE),
    # --- предоплата / залог / налог за вывод ---
    _Rule("предоплата / залог", (_w("предоплат задат"),)),
    _Rule(
        "предоплата / залог",
        (_w("залог депозит гарантийн страхов"), _w("перев внес оплат скин отправ")),
    ),
    _Rule(
        "налог / штраф / комиссия",
        (_w("оплат внес заплат перев"), _w("налог пошлин штраф комисс взнос выкуп")),
    ),
    # --- пополнение баланса телефона ---
    _Rule("пополнение баланса телефона", (_w("баланс"), _w("пополни положи закин внес скин перев"))),
    _Rule("пополнение баланса телефона", (_w("баланс"), _w("мобильн мтс мегафон билайн теле2 телефон"))),
    # --- никому не говорить ---
    _Rule(
        "никому не говорить",
        (
            _w("никому не_говор не_рассказ не_сообщ не_звон не_обращ"),
            _w("родствен близк детям сын дочер муж жен банк сотрудник отделен звонк разговор друзьям полици"),
        ),
        _w("код парол смс карт данн пин cvv"),
    ),
    _Rule("никому не говорить", (_w("разглаш в_тайне"),)),
    _Rule("никому не говорить", (_w("тайн"), _w("следств разговор звонк операц расследов"))),
    _Rule(
        "не прерывать звонок",
        (_w("не_клад не_вешай не_прерыва не_выключ не_отключ не_сбрасыва"), _w("трубк звонок телефон разговор")),
    ),
    # --- ссылки, кнопки, подтверждение операций, seed-фраза ---
    _Rule(
        "переход по ссылке",
        (_w("перейд перейти пройд откро нажм зарегистр оплат скача введ"), _w("ссылк")),
        SAFE,
    ),
    _Rule("нажать цифру", (_w("нажм жмит"), _w("цифр один$ два$ ноль$ нуль$ ноль"))),
    _Rule(
        "подтверждение операций",
        (_w("подтверждай подтверждайт"), _w("операц платеж"), _w("все любые каждую приходить")),
    ),
    _Rule(
        "seed-фраза",
        (_w("секретн_фраз сид_фраз seed мнемоническ приватн_ключ фраз_восстановл"),),
    ),
)


def _words(sentence: str) -> list[str]:
    # Целые слова (stem_len=0): обрезка до 5 букв склеила бы «перевод» и «перевыпустили».
    return tokenize(sentence, stem_len=0)


def _term_in(term: str, words: list[str]) -> bool:
    parts = term.split("_")
    exact = parts[-1].endswith("$")
    if exact:
        parts[-1] = parts[-1][:-1]
    n = len(parts)
    for i in range(len(words) - n + 1):
        if all(
            (w == p) if (exact and j == n - 1) else w.startswith(p)
            for j, (w, p) in enumerate(zip(words[i : i + n], parts))
        ):
            return True
    return False


def _any(terms: tuple[str, ...], words: list[str]) -> bool:
    return any(_term_in(t, words) for t in terms)


def _sentences(text: str) -> list[str]:
    return [s.strip() for s in _SENTENCE.findall(text) if s.strip()]


def instant_flags(text: str) -> list[RuleHit]:
    """Правила по ключевым словам: список (категория, предложение) без повторов."""
    hits: list[RuleHit] = []
    seen: set[tuple[str, str]] = set()
    for sentence in _sentences(text):
        words = _words(sentence)
        for rule in _RULES:
            if (rule.label, sentence) in seen or _any(rule.veto, words):
                continue
            if all(_any(g, words) for g in rule.groups):
                seen.add((rule.label, sentence))
                hits.append(RuleHit(rule.label, sentence))
    return hits


def stage_flags(text: str, stage: Stage) -> list[RuleHit]:
    """Совпадения с asks_for этапа: доля основ фразы в предложении не меньше порога.

    label — сама фраза из asks_for («код из СМС»), quote — предложение из text.
    """
    hits: list[RuleHit] = []
    seen: set[tuple[str, str]] = set()
    for sentence in _sentences(text):
        said = set(tokenize(sentence))
        for ask in stage.asks_for:
            tokens = tokenize(ask)
            if not tokens or (ask, sentence) in seen:
                continue
            # Короткие основы («код») не совпадают с «кода»/«коды» после обрезки до 5 букв,
            # поэтому слово из asks_for засчитывается и как начало слова из речи.
            found = sum(t in said or (len(t) >= 3 and any(w.startswith(t) for w in said)) for t in tokens)
            if found / len(tokens) >= STAGE_OVERLAP:
                seen.add((ask, sentence))
                hits.append(RuleHit(ask, sentence))
    return hits


def warning_text(hits: list[RuleHit]) -> str:
    """Текст плашки: «Мошенник требует: «…»…», цитаты без повторов. Пусто, если срабатываний нет."""
    quotes: list[str] = []
    for h in hits:
        q = h.quote.strip()
        if q not in quotes:
            quotes.append(q)
    if not quotes:
        return ""
    joined = "; ".join(f"«{q}»" for q in quotes)
    return f"Мошенник требует: {joined}. Ничего не называй и не переводи."
