def test_zero_hits_on_normal_eval_calls():
    """Главное требование: ни одного срабатывания на репликах caller обычных звонков."""
    cases = [json.loads(line) for line in (ROOT / "data/eval/cases.jsonl").read_text().splitlines() if line]
    normal = [c for c in cases if c["expected_scheme"] is None]
    assert normal
    for c in normal:
        for u in c["utterances"]:
            if u["speaker"] == "caller":
                assert instant_flags(u["text"]) == [], (c["id"], u["text"])


def test_quote_is_verbatim_sentence():
    text = "Здравствуйте, это служба безопасности. Продиктуйте код из смс. Спасибо."
    hits = instant_flags(text)
    assert hits == [RuleHit("код из СМС", "Продиктуйте код из смс.")]
    assert all(h.quote in text for h in hits)


def test_no_duplicates():
    hits = instant_flags("Переведите деньги. Переведите деньги.")
    assert len(hits) == len(set(hits))


def make_stage(asks: list[str]) -> Stage:
    return Stage(
        n=3,
        name="Требование",
        goal="Получить доступ",
        typical_phrases=[f"фраза {i}" for i in range(5)],
        red_flags=["флаг"],
        asks_for=asks,
        next_move="дальше",
    )


def test_stage_flags_matches_asks_for():
    stage = make_stage(["код из СМС", "перевод по СБП", "предоплата"])
    hits = stage_flags("Продиктуйте, пожалуйста, коды из смс. Как погода?", stage)
    assert [h.label for h in hits] == ["код из СМС"]
    assert hits[0].quote == "Продиктуйте, пожалуйста, коды из смс."
    assert stage_flags("Нужна предоплата", stage)[0].label == "предоплата"
    assert stage_flags("Какой сегодня хороший день", stage) == []


def test_warning_text():
    hits = [
        RuleHit("код из СМС", "Продиктуйте код."),
        RuleHit("перевод денег", "Продиктуйте код."),
        RuleHit("перевод денег", "Переведите деньги."),
    ]
    text = warning_text(hits)
    assert text == "Мошенник требует: «Продиктуйте код.»; «Переведите деньги.». Ничего не называй и не переводи."
    assert warning_text([]) == ""
